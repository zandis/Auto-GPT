def test_the_round2_sets_are_what_d1256_counts() -> None:
    """D-1256 §8 counts 75 claims and 75 honest lines per language in the development set, 12 of each per class and 3
    of each for quotations; 20 and 20 held out; 33 and 32 probes."""
    for rows in (ROUND2_EN, ROUND2_JA):
        assert len(rows) == 150 and len({t for _, t, _ in rows}) == 150
        assert sum(k for *_, k in rows) == 75
        for cls in ("efficacy", "prevent", "decide", "state", "directive", "stage"):
            assert sum(1 for c, _, k in rows if c == cls and k) == 12
            assert sum(1 for c, _, k in rows if c == cls and not k) == 12
    for rows in (HELD_OUT_EN, HELD_OUT_JA):
        assert len(rows) == 40 and sum(k for *_, k in rows) == 20
    assert (len(PROBE_EN), len(PROBE_JA)) == (33, 32)


