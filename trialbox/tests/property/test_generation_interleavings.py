"""T-725 (D-491; lifecycle review F-4, proposal G-4): a property test over interleavings of the night's steps.

The night's steps that build a derived artefact (the FHIR store's load, the derive batch, the twin build, the vector
index) each start (``begin``) and end (``finish``), for whatever generation the step that called them was given:
tonight's, a site publish's new generation of the same date, a late re-run of an earlier night. Steps of different
generations interleave, and any of them may die between its start and its end.

For every generated interleaving, against the real ledger (``datacore.generations.Built``, PostgreSQL) and a
five-line model of it:

1. the generation an artefact is built from never goes back (an older generation never overwrites a newer one);
2. ``readable(artefact, G)`` is ``ok`` exactly when the model says the artefact's last accepted build was from G
   and finished: never an older artefact read as the job's, never a newer one, never a half-built one;
3. a refused start and an overtaken finish change nothing;
4. when every step of the newest generation has run to its end, a job pinned to it may read everything, and a job
   pinned to any other generation may read nothing.

The interleavings are generated by plain Python with fixed seeds (``hypothesis`` is not in the test lock; T-737)."""

from __future__ import annotations

import random
import threading
from typing import Any

import pytest
from datacore.generations import Built, guarded
from tb_common.generation import ARTEFACTS, BUILDING, FINISHED, Generation, OlderGeneration, verdict

GENERATIONS = [  # an earlier night and its late re-run, tonight, tonight after a site publish, a bare date
    Generation("2026-10-03", 1),
    Generation("2026-10-03", 2),
    Generation("2026-10-04"),
    Generation("2026-10-04", 1),
    Generation("2026-10-04", 2),
]
NEWEST = max(GENERATIONS)
SEEDS = range(40)
STEPS = 60


def interleaving(seed: int) -> list[tuple[str, str, Generation]]:
    """``(event, artefact, generation)``: a ``begin`` of any generation at any time; a ``finish`` only of a build
    that began (in any order, possibly never: the step died)."""
    rng = random.Random(seed)
    began: list[tuple[str, Generation]] = []
    out: list[tuple[str, str, Generation]] = []
    for _ in range(STEPS):
        if began and rng.random() < 0.45:
            a, g = began.pop(rng.randrange(len(began)))
            out.append(("finish", a, g))
        else:
            a, g = rng.choice(ARTEFACTS), rng.choice(GENERATIONS)
            began.append((a, g))
            out.append(("begin", a, g))
    return out


class Model:
    """What the ledger must hold: per artefact, the generation of its last accepted start and whether that build
    finished."""

    def __init__(self) -> None:
        self.rows: dict[str, tuple[Generation, str]] = {}

    def begin(self, a: str, g: Generation) -> bool:
        if a in self.rows and g < self.rows[a][0]:
            return False
        self.rows[a] = (g, BUILDING)
        return True

    def finish(self, a: str, g: Generation) -> bool:
        if a in self.rows and self.rows[a][0] == g:
            self.rows[a] = (g, FINISHED)
            return True
        return False


@pytest.fixture
def ledger(db_url: str) -> Any:
    with Built(db_url) as b:
        yield b


def test_no_interleaving_moves_an_artefact_back_or_lets_a_job_read_another_generation(ledger: Built) -> None:
    checked = refused = overtaken = 0
    for seed in SEEDS:
        ledger._db.execute("DELETE FROM built")  # each interleaving starts on a box that built nothing
        model = Model()
        high: dict[str, Generation] = {}
        for event, a, g in interleaving(seed):
            before = ledger.state(a)
            if event == "begin":
                ok = model.begin(a, g)
                if ok:
                    assert ledger.begin(a, g) == g
                else:
                    with pytest.raises(OlderGeneration):
                        ledger.begin(a, g)
                    assert ledger.state(a) == before  # property 3
                    refused += 1
            else:
                ok = model.finish(a, g)
                assert ledger.finish(a, g) is ok
                if not ok:
                    assert ledger.state(a) == before  # property 3
                    overtaken += 1
            got = ledger.state(a)
            assert got == model.rows.get(a), (seed, event, a, g)
            if got is not None:  # property 1
                assert got[0] >= high.get(a, got[0]), (seed, a, got, high)
                high[a] = got[0]
            for pinned in GENERATIONS:  # property 2
                want = a in model.rows and model.rows[a] == (pinned, FINISHED)
                assert ledger.readable(a, pinned).ok is want, (seed, event, a, g, pinned)
                checked += 1
        # property 4: the night's steps of the newest generation all run to their end
        for a in ARTEFACTS:
            ledger.begin(a, NEWEST)
            assert ledger.finish(a, NEWEST)
        assert all(ledger.readable_all(NEWEST).values())
        for other in GENERATIONS:
            if other != NEWEST:
                assert not any(ledger.readable_all(other).values()), other
    assert checked > 10_000 and refused > 100 and overtaken > 100  # the interleavings did reach every case


def _start(db_url: str, gate: threading.Barrier, results: dict[str, Any], name: str, g: Generation) -> None:
    with Built(db_url) as mine:
        gate.wait()
        try:
            mine.begin("derived", g)
            results[name] = "began"
        except OlderGeneration:
            results[name] = "refused"


def test_two_builds_started_at_once_end_on_the_newer_generation(db_url: str) -> None:
    """Two processes start a build of the same artefact from different generations at the same moment, many times:
    whatever the order, the artefact ends on the newer one, and the older build's finish finishes nothing."""
    old, new = Generation("2026-10-04", 1), Generation("2026-10-04", 2)
    for _ in range(25):
        with Built(db_url) as b:
            b._db.execute("DELETE FROM built")
        gate = threading.Barrier(2)
        results: dict[str, Any] = {}
        threads = [
            threading.Thread(target=_start, args=(db_url, gate, results, name, g))
            for name, g in (("old", old), ("new", new))
        ]
        for t in threads:
            t.start()
        for t in threads:
            t.join()
        with Built(db_url) as b:
            assert results["new"] == "began" and b.state("derived") == (new, BUILDING), results
            assert b.finish("derived", old) is False and b.state("derived") == (new, BUILDING)
            assert b.finish("derived", new) and b.readable("derived", new) and not b.readable("derived", old)


def test_a_builder_is_run_recorded_refused_and_left_unfinished_when_it_dies(db_url: str) -> None:
    ran: list[str] = []

    def build(name: str) -> Any:
        def run() -> str:
            ran.append(name)
            return name

        return run

    assert guarded("twin", "2026-10-04.g2", build("tonight"), db_url) == "tonight"
    with Built(db_url) as b:
        assert b.state("twin") == (Generation("2026-10-04", 2), FINISHED)
    # a late re-run of an earlier night: its builder does not run, the newer twins stay (F-4)
    assert guarded("twin", "2026-10-03.g5", build("older night"), db_url) is None and ran == ["tonight"]
    assert guarded("twin", "2026-10-04", build("the bare date"), db_url) is None and ran == ["tonight"]

    def dies() -> None:
        raise RuntimeError("the builder died")

    with pytest.raises(RuntimeError):
        guarded("twin", "2026-10-05.g1", dies, db_url)
    with Built(db_url) as b:  # begun, never finished: nobody may read it, not even a job on that generation
        assert b.state("twin") == (Generation("2026-10-05", 1), BUILDING)
        assert (
            not b.readable("twin", "2026-10-05.g1")
            and "still being built" in b.readable("twin", "2026-10-05.g1").reason
        )
        assert "a newer generation" in b.readable("twin", "2026-10-04.g2").reason
        assert "never built" in b.readable("vec", "2026-10-05.g1").reason
        with pytest.raises(ValueError, match="unknown artefact"):
            b.begin("lake", "2026-10-05")
    assert guarded("twin", "2026-10-05.g1", build("retry"), db_url) == "retry"  # the same generation again: a retry


@pytest.mark.nodb
def test_the_order_of_generations_and_the_one_rule() -> None:
    g = Generation.parse
    assert g("2026-10-04") < g("2026-10-04.g1") < g("2026-10-04.g2") < g("2026-10-04.g10") < g("2026-10-05")
    assert str(g("2026-10-04.g3")) == "2026-10-04.g3" and str(g("2026-10-04")) == "2026-10-04"
    assert g("2026-10-04") == Generation("2026-10-04", 0)
    for bad in ("", "2026-10-04.g0", "a b", "2026-10-04.g"):
        with pytest.raises(ValueError):
            g(bad)
    pinned = g("2026-10-04.g2")
    assert verdict("derived", pinned, pinned, FINISHED).ok
    assert not verdict("derived", pinned, pinned, BUILDING)
    assert "an older" in verdict("derived", pinned, g("2026-10-04.g1"), FINISHED).reason
    assert "a newer" in verdict("derived", pinned, g("2026-10-05.g1"), FINISHED).reason
    assert "never built" in verdict("derived", pinned, None, None).reason
