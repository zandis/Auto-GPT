"""The judge in the loop: no path excludes a patient the full record keeps (T-706, D-460; review 2026-11-12 AD-6).

TB-PLAN-06 §7.4: "cutting a record never turns unknown or kept into not matched"; "an unknown stays unknown". The
safety properties of ``tests/unit/test_safety_properties.py`` ran with a judge that answers by criterion whatever the
excerpts say, so no property about the text could fail there (review ``decision.md`` answer 4). Here the scripted
pair READS the text it is shown, on every path that reads notes:

* the oracle knows each synthetic patient's truth from the full record (the decisive sentence of the inclusion and of
  the exclusion is in one of its window notes, or nowhere);
* each model of the pair answers only from its prompt's excerpts: "met" when the decisive sentence is shown, else a
  confident "not met" quoting what it was shown (:func:`reader`);
* a patient may be excluded only when the full record makes the patient ineligible AND two different models agreed
  (:func:`may_exclude`). Every other exclusion is a violation, whatever the path cut, lost, re-tiered or replayed.

Paths, each through its own entry point on a real lake (``tests/judge_kit.py: note_lake``): SCREEN v1
(``evaluate_scope``), SCREEN cascade (``screen_with_cascade``), MICROBATCH re-tier of the pool row SCREEN stored
(``microbatch.run``), NAV (``nav.run`` up to publishing) and CASE (``evaluate_case``). Operations: :data:`OPS`.

Today's defects are strict expected failures by finding id (:data:`EXPECTED`): the suite fails when one starts
passing, so the card that fixes it removes its line. At the end of wave D (T-707, T-709, T-710) the table is empty.

The charts are generated by plain Python with a fixed seed (:func:`charts`): ``hypothesis`` is not in the test lock
(T-737 adds it). ``Chart`` is a frozen value built from five small integers, so T-737 turns :func:`charts` into a
strategy in a few lines (``st.builds(Chart, ...)`` over the same ranges) and the properties stay as they are.
"""

