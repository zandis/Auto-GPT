# ------------------------------------------------------------------------------------------------ the charts
@dataclass(frozen=True)
class Chart:
    """One synthetic patient: 1 to 4 window notes of ``lines[i]`` filler sentences each; the decisive sentence of
    the inclusion in note ``inc_at`` (None: nowhere), of the exclusion in ``exc_at``; ``bait_at``: a note (never
    ``inc_at``) holding a lexicon hit for :data:`INC_LEX` that decides nothing."""

    pid: str
    lines: tuple[int, ...]
    inc_at: int | None
    exc_at: int | None
    bait_at: int | None = None

    def did(self, i: int) -> str:
        return f"{self.pid}-d{i + 1}"  # ``note_lake`` numbers a patient's notes from 1

    def day(self, i: int) -> date:
        return IDX - timedelta(days=10 + 37 * i)  # all inside the year before the index date

    def text(self, i: int) -> str:
        out = [f"Visit {i + 1} routine line {m}." for m in range(1, self.lines[i] + 1)]
        mid = len(out) // 2
        for at, sentence in ((self.inc_at, S_INC), (self.exc_at, S_EXC)):
            if at == i:
                out.insert(mid, sentence)
        if self.bait_at == i:
            out.append(BAIT)
        return "\n".join(out)

    def notes(self) -> list[tuple[date, str]]:
        return [(self.day(i), self.text(i)) for i in range(len(self.lines))]

    @property
    def ineligible(self) -> bool:
        """The full record's answer: the inclusion not met, or the exclusion present."""
        return self.inc_at is None or self.exc_at is not None

    def decisive_dids(self) -> set[str]:
        return {self.did(i) for i in (self.inc_at, self.exc_at) if i is not None}


def charts(seed: int = SEED, n: int = 36) -> list[Chart]:
    """``n`` generated charts (T-737: the strategy) after five named ones that make each operation bite."""
    named = [
        Chart("N-CUT", (30, 30, 2), inc_at=2, exc_at=None),  # 7 chunks, 60 filler sentences: any top 5 can miss it
        Chart("N-BAIT", (3, 3), inc_at=1, exc_at=None, bait_at=0),  # the lexicon hit is in the other note
        Chart("N-EXC", (5,), inc_at=0, exc_at=0),  # ineligible: only a pair may exclude
        Chart("N-NONE", (4, 4), inc_at=None, exc_at=None),  # ineligible: the control a pair excludes
        Chart("N-KEEP", (2,), inc_at=0, exc_at=None),  # eligible, one short note
    ]
    rng = random.Random(seed)
    out = []
    for k in range(n):
        lines = tuple(rng.randint(0, 40) for _ in range(rng.randint(1, 4)))
        notes = range(len(lines))
        inc_at = rng.choice([None, *notes, *notes])  # met in most charts
        exc_at = rng.choice([None, None, None, *notes])
        bait = [i for i in notes if i != inc_at]
        bait_at = rng.choice([None, *bait]) if bait else None
        out.append(Chart(f"G-{k:02d}", lines, inc_at, exc_at, bait_at))
    return named + out


