def _batches(pids: list[str], size: int) -> Iterator[list[str]]:
    for i in range(0, len(pids), size):
        yield pids[i : i + size]


@pytest.mark.parametrize("path", ["screen_v1", "screen_cascade"])  # NAV scopes by appointment, not by a given list
@pytest.mark.parametrize("size", [1, 7])
def test_a_batch_split_gives_the_same_statuses(
    lake: LakeLocal, path: str, size: int, monkeypatch: pytest.MonkeyPatch
) -> None:
    """The patients in batches of ``size`` (T-694's batching) get the statuses of one run over everyone."""
    whole = PATHS[path](_run(lake, OPS["shown"], monkeypatch), monkeypatch)
    split: dict[str, str] = {}
    for part in _batches(PIDS, size):
        r = _run(lake, OPS["shown"], monkeypatch)
        r.pids = part
        got = PATHS[path](r, monkeypatch)
        split.update({p: got[p] for p in part})
    assert split == whole
    assert not violations(split, "pair")


