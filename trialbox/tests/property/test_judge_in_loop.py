@dataclass
class Run:
    """One run's inputs: the lake as the path sees it, the two models, the ruleset, the cascade's S2b ranking."""

    lake: World
    llm: Any
    verifier: Any
    rs: Ruleset = field(default_factory=lambda: RS)
    embed: str = "first"
    pids: list[str] = field(default_factory=lambda: list(PIDS))


def screen_v1(r: Run, mp: pytest.MonkeyPatch) -> dict[str, str]:
    ctx = _ctx(r.lake, r.llm, r.verifier)
    try:
        res = evaluate_scope(ctx, r.rs, IDX, SNAP, [Scoped(p, None, None, None) for p in r.pids])
    except StepFailed:
        return dict.fromkeys(r.pids, "refused")
    return {p: pv.tier for p, pv in res.items()}


def _cascade(r: Run, mp: pytest.MonkeyPatch) -> Any:
    import embed_service.embedder

    mp.setattr(embed_service.embedder, "HashEmbedder", ranking_embedder(r.embed))
    ctx = _ctx(r.lake, r.llm, r.verifier)
    nj = judge_for(ctx, r.rs)
    return ctx, screen_with_cascade(ctx, r.rs, IDX, SNAP, r.pids, nj, judging_info(nj), threshold(ctx, r.rs), 12)


def screen_cascade(r: Run, mp: pytest.MonkeyPatch) -> dict[str, str]:
    try:
        _, cs = _cascade(r, mp)
    except StepFailed:
        return dict.fromkeys(r.pids, "refused")
    return {p: pv.tier for p, pv in cs.results.items()}


def microbatch_retier(r: Run, mp: pytest.MonkeyPatch, now: Run) -> dict[str, str]:
    """SCREEN (cascade) under ``r`` stores the pool; next week MICROBATCH re-tiers the stored rows under ``now``."""
    stored: list[dict[str, Any]] = []
    try:
        ctx, cs = _cascade(r, mp)
    except StepFailed:
        return dict.fromkeys(r.pids, "refused")
    rows = [row(pv, None, None, None, "2026-10-05T10:00:00+09:00") for pv in cs.results.values()]
    persist_pool(_ctx(r.lake, r.llm, r.verifier, job_id="J-SCREEN", sink=stored), r.rs, rows)
    seen: list[Any] = []

    class _Stop(Exception):
        pass

    def stop(ctx: Any, rs: Any, rows: list[Any]) -> None:
        seen.extend(rows)
        raise _Stop

    mp.setattr(microbatch, "require_open", lambda ruleset: None)
    mp.setattr(microbatch, "require_approved", lambda ctx, rs, v: r.rs)
    mp.setattr(microbatch, "persist_pool", stop)
    ctx = _ctx(now.lake, now.llm, now.verifier, job_id="J-MB", options={"incident": "0"}, pool=stored)
    with pytest.raises(_Stop):
        microbatch.run(ctx)
    return {x.pid: x.tier for x in seen}


def nav_run(r: Run, mp: pytest.MonkeyPatch) -> dict[str, str]:
    """``nav.run`` up to publishing: per patient the sheet (listed), a row of things to confirm, or nothing."""
    out: dict[str, str] = {}
    real = nav.classify

    def spy(rs: Ruleset, pv: Any, *a: Any) -> Any:
        name, missing = real(rs, pv, *a)
        out[pv.pid] = "listed" if name else ("confirm" if missing else "excluded")
        return name, missing

    class _Stop(Exception):
        pass

    def stop(ctx: Any, pids: Any, where: str) -> frozenset[str]:
        raise _Stop

    rs = _nhi(r.rs)
    mp.setattr(nav, "require_approved", lambda ctx, rid, v: rs)
    mp.setattr(nav, "classify", spy)
    mp.setattr(nav, "opted_out_now", stop)
    try:
        with pytest.raises(_Stop):
            nav.run(_ctx(r.lake, r.llm, r.verifier, options={"dept": "RHEUM"}))
    except StepFailed:
        return dict.fromkeys(r.pids, "refused")
    assert set(out) == set(PIDS), "NAV no longer calls classify: read its status from the one status function (T-709)"
    return {p: out[p] for p in r.pids}


def case_run(r: Run, mp: pytest.MonkeyPatch) -> dict[str, str]:
    """CASE on each chart uploaded whole (no chart number): a criterion printed "not met" takes the patient off."""
    out = {}
    for pid in r.pids:
        c = BY_PID[pid]
        chart = [{"date": c.day(i).isoformat(), "did": c.did(i), "text": c.text(i), "note_type": "progress"}
                 for i in range(len(c.lines))]  # fmt: skip
        rows, _ = case_mod.evaluate_case(_ctx(r.lake, r.llm, r.verifier), r.rs, case_mod.Subject(), chart, "en")
        out[pid] = "excluded" if any(x["verdict"] == "fail" for x in rows) else "kept"
    return out


