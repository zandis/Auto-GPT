@dataclass
class World:
    """The real lake of the charts, with a retrieval ranking a test chooses (the v1 path's ``chunks_search``) and the
    appointment and claim tables NAV and MICROBATCH read."""

    inner: LakeLocal
    ranking: str = "first"  # first | last | lost: the decisive chunks first, last, or never indexed

    def snapshot(self) -> str:
        return SNAP

    def query(self, sql: str, params: list[Any] | None = None, snapshot: str | None = None) -> pa.Table:
        p = params or []
        if sql == nav.SCOPE_SQL:
            return pa.Table.from_pylist([{"pid": pid, "next_appt": f"{IDX + timedelta(days=3)} 09:00:00",
                                          "practitioner_id": "DR-1", "dept": "RHEUM"} for pid in PIDS])  # fmt: skip
        if "FROM claim" in sql:
            return pa.Table.from_pylist([])  # no approval, no application: NAV's "likely eligible" question
        if sql == microbatch.APPT_SQL:
            when = datetime(2026, 10, 8, 9, 0)
            return pa.Table.from_pylist([{"pid": pid, "next_appt": when, "practitioner_id": "DR-1",
                                          "dept": "RHEUM"} for pid in p[0]])  # fmt: skip
        return self.inner.query(sql, p, snapshot)

    def chunks_search(
        self,
        pid: str,
        query: str,
        k: int = 5,
        date_from: date | None = None,
        date_to: date | None = None,
        snapshot: str | None = None,
    ) -> list[dict[str, Any]]:
        """Every chunk of the patient's window, ranked by the test's choice, the top ``k``: what any retrieval
        ranking may return (the real one fuses BM25 and vectors, ``Lake.search``)."""
        lo = (date_from or IDX - timedelta(days=365)).isoformat()
        hi = (date_to or IDX).isoformat()
        rows = self.inner.query(
            "SELECT did, chunk_no, text, CAST(date AS DATE) AS d, type FROM document_chunk WHERE pid = $1 "
            "AND CAST(date AS DATE) BETWEEN CAST($2 AS DATE) AND CAST($3 AS DATE) ORDER BY did, chunk_no",
            [pid, lo, hi],
            snapshot,
        ).to_pylist()
        hits = [{"did": r["did"], "chunk_no": r["chunk_no"], "text": r["text"], "date": r["d"].isoformat(),
                 "type": r["type"], "note_type": r["type"]} for r in rows]  # fmt: skip

        def decisive(h: dict[str, Any]) -> bool:
            return S_INC in h["text"] or S_EXC in h["text"]

        if self.ranking == "lost":
            gone = BY_PID[pid].decisive_dids()
            hits = [h for h in hits if h["did"] not in gone]
        else:
            hits.sort(key=lambda h: decisive(h) == (self.ranking == "last"))
        return hits[:k]


def ranking_embedder(mode: str) -> type:
    """The cascade's S2b embedder (``screen_with_cascade`` builds ``HashEmbedder()``): every sentence of a note that
    holds a decisive sentence ranked last (``last``), or the decisive sentences first (``first``)."""
    low = {s for c in CHARTS for i in range(len(c.lines)) if c.did(i) in c.decisive_dids()
           for s in c.text(i).splitlines()}  # fmt: skip

    class Ranked:
        model = f"ranked-{mode}"

        def embed(self, texts: list[str]) -> list[list[float]]:
            def v(s: str) -> list[float]:
                if mode == "first":
                    return [1.0, 0.0] if s.strip() in (S_INC, S_EXC) else [0.6, 0.8]
                return [0.0, 1.0] if s.strip() in low else [0.6, 0.8]

            return [[1.0, 0.0], *[v(s) for s in texts[1:]]]

    return Ranked


