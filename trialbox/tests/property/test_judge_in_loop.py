def may_exclude(c: Chart, verifier: str) -> bool:
    """The oracle: the full record makes the patient ineligible and two different models read it and agree. A
    verifier that is down now and then (``down``) is a pair when it answers; when it does not, the pair rule makes
    the answer unknown (``tb_common.pair.combine``), which this property covers from the other side."""
    return c.ineligible and verifier in ("pair", "down")


# ------------------------------------------------------------------------------------------------ the oracle pair
def reader(variables: dict[str, Any]) -> dict[str, Any]:
    """One model that answers only from the text it is shown (the judge prompt's JSON)."""
    sentence = DECISIVE.get(str(variables["criterion_text"]))
    excerpts = variables["excerpts"]
    if sentence is None or not excerpts:  # a question it has no sentence for (CASE asks the age): no answer
        return {"verdict": "unknown", "reason": "not in the text", "confidence": 0.3, "quote": None,
                "quote_date": None}  # fmt: skip
    hit = next((e for e in excerpts if sentence in str(e["text"])), None)
    if hit is not None:
        return {"verdict": "pass", "reason": "read", "confidence": 0.95, "quote": sentence,
                "quote_date": str(hit["date"])}  # fmt: skip
    first = excerpts[0]
    quote = next(ln.strip() for ln in str(first["text"]).splitlines() if ln.strip())
    return {"verdict": "fail", "reason": "not in what I read", "confidence": 0.95, "quote": quote,
            "quote_date": str(first["date"])}  # fmt: skip


def contrarian(variables: dict[str, Any]) -> dict[str, Any]:
    out = reader(variables)
    out["verdict"] = {"pass": "fail", "fail": "pass"}.get(out["verdict"], out["verdict"])
    return out


def flaky(variables: dict[str, Any]) -> dict[str, Any]:
    """A verifier that is down for about one prompt in twelve (under the 10 % that fails the whole job)."""
    key = json.dumps([variables["criterion_text"], [e["text"] for e in variables["excerpts"]]])
    if int(hashlib.sha256(key.encode()).hexdigest(), 16) % 12 == 0:
        raise LlmError("LLM endpoint unreachable (local): scripted outage")
    return reader(variables)


class Model(ScriptedModel):
    """A scripted model that can tell its context (``budget`` tokens of notes, :meth:`NoteJudge.budget`)."""

    def __init__(self, model: str, answer: Callable[[dict[str, Any]], dict[str, Any]], *, served: str | None = None,
                 budget: int | None = None) -> None:  # fmt: skip
        super().__init__(model, answer, served=served)
        self.budget = budget

    def text_budget(self, prompt: str, fixed: dict[str, Any]) -> int | None:
        return self.budget


@dataclass
class Tape:
    """Every answer of a run, by model and prompt; a replay answers from it (an unrecorded prompt: the model is
    down)."""

    answers: dict[str, dict[str, Any]] = field(default_factory=dict)

    @staticmethod
    def key(model: str, v: dict[str, Any]) -> str:
        return json.dumps([model, v["criterion_text"], [e["text"] for e in v["excerpts"]]])

    def record(self, model: str) -> Callable[[dict[str, Any]], dict[str, Any]]:
        def answer(v: dict[str, Any]) -> dict[str, Any]:
            self.answers[self.key(model, v)] = out = reader(v)
            return out

        return answer

    def replay(self, model: str) -> Callable[[dict[str, Any]], dict[str, Any]]:
        def answer(v: dict[str, Any]) -> dict[str, Any]:
            got = self.answers.get(self.key(model, v))
            if got is None:
                raise LlmError("LLM endpoint unreachable (local): not on the tape")
            return dict(got)

        return answer


def models(verifier: str, budget: int | None = None, tape: Tape | None = None, replay: bool = False) -> tuple[Any, Any]:
    """(judge, verifier) for a verifier state: ``pair`` (two models), ``single`` (none), ``down`` (one that is down
    now and then), ``disagree`` (one that reads the opposite), ``same_build`` (the judge's model under another name)."""
    if tape is not None:
        how = tape.replay if replay else tape.record
        return Model("judge-a", how("judge-a")), Model("verifier-b", how("verifier-b"))
    judge = Model("judge-a", reader, budget=budget)
    if verifier == "single":
        return judge, None
    answer = {"pair": reader, "down": flaky, "disagree": contrarian, "same_build": reader}[verifier]
    served = "judge-a" if verifier == "same_build" else None
    return judge, Model("verifier-b", answer, served=served, budget=budget)


