"""``python -m console.cli``: console accounts and operate actions from the shell (FR-UX-22: every control-plane
action is also a command, with the same audit).

    bootstrap-admin [--username admin] [--mailbox you@hospital] [--password-stdin]
        First administrator. Without --password-stdin a random password is generated and printed once.
        Does nothing (exit 0) when an administrator exists.
    add-user NAME --role admin|viewer [--mailbox ADDR] [--password-stdin]
    reset-password NAME [--password-stdin]
    disable NAME
    list-users
    ingest                      load the configured source (synthetic site A in the POC) through the adapter
    poc-settings --in FILE --out FILE --admin-email ADDR [--rate-limit N]
        POC settings: the example settings with the administrator's mailbox added to the senders and reviewers.
    poc-openrouter-pin --model ID --out FILE [--build nemotron-3-nano-candidate]
        DEV-only registry site override: the j-workhorse build served by OpenRouter as model ID. There are no weights
        to hash, so the pin is sha256("openrouter:" + ID): it fixes which hosted model answers, nothing more.
"""

from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path
from typing import Any

import yaml

from console.auth import AuthError, UserStore, random_password

DATA = Path(os.environ.get("TB_CONSOLE_DIR", "/data/console"))


def _audit(event: str, **fields: Any) -> None:
    from tb_common.audit import AuditLog

    directory = Path(os.environ.get("TB_AUDIT_DIR", "/data/audit"))
    try:
        AuditLog(directory, os.environ.get("TB_TZ", "Asia/Taipei")).append(event, actor="console-cli", **fields)
    except OSError as exc:  # no audit volume (developer shell): say so, never fail silently
        print(f"warning: audit not written ({exc})", file=sys.stderr)


def _password(args: argparse.Namespace) -> tuple[str, bool]:
    if args.password_stdin:
        return sys.stdin.readline().rstrip("\n"), False
    return random_password(), True


def poc_settings(src: Path, out: Path, admin: str, rate_limit: int) -> None:
    doc = yaml.safe_load(src.read_text(encoding="utf-8"))
    admin = admin.strip().lower()
    senders = doc.setdefault("allowlist", {}).setdefault("senders", [])
    if admin not in senders:
        senders.append(admin)
    reviewers = doc.setdefault("reviewers", [])
    if admin not in reviewers:
        reviewers.append(admin)
    domain = admin.rsplit("@", 1)[-1]
    internal = doc.setdefault("internal_domains", [])
    if domain not in internal:
        internal.append(domain)
    doc["rate_limit_per_sender_per_day"] = rate_limit
    out.parent.mkdir(parents=True, exist_ok=True)
    header = "# Generated by console.cli poc-settings from the example settings (synthetic POC site). Edit freely.\n"
    out.write_text(header + yaml.safe_dump(doc, allow_unicode=True, sort_keys=False), encoding="utf-8")


def _openrouter_build() -> str:
    """The registry's hosted j-workhorse build for OpenRouter when there is one, else the Nemotron candidate."""
    from registry.registry import DEFAULT_PATH

    builds = (yaml.safe_load(Path(DEFAULT_PATH).read_text(encoding="utf-8")) or {}).get("builds") or []
    hosted = [
        str(b["build_id"])
        for b in builds
        if b.get("alias") == "j-workhorse" and "openrouter" in (b.get("served") or {}) and b.get("serving") == "hosted"
    ]
    for want in ("or-nemotron-3-nano-30b-a3b", *hosted):
        if want in hosted:
            return want
    return "nemotron-3-nano-candidate"


def openrouter_pin(model: str, build: str, out: Path) -> str:
    """Pin ``build`` to OpenRouter ``model`` in a site override; returns the pin (sha256).

    A ``serving: hosted`` build is pinned the registry's way, by a dated provider descriptor (``tools.pin_provider``,
    public model list, no API key); an older non-hosted candidate gets a plain served-name pin."""
    import hashlib

    from registry.registry import DEFAULT_PATH

    builds = (yaml.safe_load(Path(DEFAULT_PATH).read_text(encoding="utf-8")) or {}).get("builds") or []
    entry: dict[str, Any] = next((b for b in builds if b.get("build_id") == build), {})
    if entry.get("serving") == "hosted":
        from tools.pin_provider import main as pin_provider

        if pin_provider(["--build", build, "--model", model, "--out", str(out)]) != 0:
            raise SystemExit(f"poc-openrouter-pin: tools.pin_provider could not pin {build} to {model}")
        pinned = (yaml.safe_load(out.read_text(encoding="utf-8")) or {}).get("builds", {}).get(build, {})
        return str(pinned.get("sha256") or "")
    sha = hashlib.sha256(f"openrouter:{model}".encode()).hexdigest()
    doc = {
        "kind": "registry-site-override",
        "builds": {build: {"served": {"openrouter": model}, "sha256": sha}},
    }
    out.parent.mkdir(parents=True, exist_ok=True)
    header = "# DEV-only OpenRouter pin written by console.cli poc-openrouter-pin (D0 synthetic data only).\n"
    out.write_text(header + yaml.safe_dump(doc, sort_keys=False), encoding="utf-8")
    return sha


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="console.cli", description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    b = sub.add_parser("bootstrap-admin")
    b.add_argument("--username", default="admin")
    b.add_argument("--mailbox", default=os.environ.get("TB_CONSOLE_ADMIN_EMAIL", ""))
    b.add_argument("--password-stdin", action="store_true")
    a = sub.add_parser("add-user")
    a.add_argument("name")
    a.add_argument("--role", choices=("admin", "viewer"), required=True)
    a.add_argument("--mailbox", default="")
    a.add_argument("--password-stdin", action="store_true")
    r = sub.add_parser("reset-password")
    r.add_argument("name")
    r.add_argument("--password-stdin", action="store_true")
    d = sub.add_parser("disable")
    d.add_argument("name")
    sub.add_parser("list-users")
    sub.add_parser("ingest")
    p = sub.add_parser("poc-settings")
    p.add_argument("--in", dest="src", type=Path, required=True)
    p.add_argument("--out", type=Path, required=True)
    p.add_argument("--admin-email", required=True)
    p.add_argument("--rate-limit", type=int, default=1000)
    o = sub.add_parser("poc-openrouter-pin")
    o.add_argument("--model", required=True)
    o.add_argument("--build", default="auto", help="registry build to pin (auto: an OpenRouter j-workhorse build)")
    o.add_argument("--out", type=Path, required=True)
    args = ap.parse_args(argv)

    if args.cmd == "poc-openrouter-pin":
        build = args.build if args.build != "auto" else _openrouter_build()
        sha = openrouter_pin(args.model, build, args.out)
        print(f"wrote {args.out}: {build} -> openrouter:{args.model} (pin {sha[:12]})")
        return 0

    if args.cmd == "poc-settings":
        poc_settings(args.src, args.out, args.admin_email, args.rate_limit)
        print(f"wrote {args.out}")
        return 0
    if args.cmd == "ingest":
        from tb_common.config import get_config
        from tb_common.objstore import from_config

        from console.backend import HttpBackend

        cfg = get_config()
        from tb_common.audit import AuditLog

        backend = HttpBackend(cfg, from_config(), AuditLog(cfg.env.audit_path, cfg.env.tz))
        _audit("console.operate", detail={"action": "ingest"})
        rep = backend.ingest()
        _audit("console.operate", detail={"action": "ingest.done", "reason": "passed" if rep.get("passed") else "no"})
        print({k: rep.get(k) for k in ("passed", "snapshot", "counts", "fhir_loaded")})
        return 0 if rep.get("passed") else 1

    store = UserStore(DATA / "console.sqlite")
    try:
        if args.cmd == "bootstrap-admin":
            if store.count("admin") > 0:
                print("console: an administrator exists already (use reset-password to set a new password)")
                return 0
            pw, generated = _password(args)
            store.create(args.username, "admin", pw, args.mailbox or None)
            _audit("console.user", detail={"action": "create", "role": "admin"})
            print(
                f"console: administrator '{args.username}' created"
                + (f" (mailbox {args.mailbox})" if args.mailbox else "")
            )
            if generated:
                print(f"console: password (shown once): {pw}")
        elif args.cmd == "add-user":
            pw, generated = _password(args)
            store.create(args.name, args.role, pw, args.mailbox or None)
            _audit("console.user", detail={"action": "create", "role": args.role})
            print(f"console: user '{args.name}' ({args.role}) created")
            if generated:
                print(f"console: password (shown once): {pw}")
        elif args.cmd == "reset-password":
            pw, generated = _password(args)
            store.set_password(args.name, pw)
            _audit("console.user", detail={"action": "reset-password"})
            print(f"console: password of '{args.name}' changed; all sessions ended")
            if generated:
                print(f"console: password (shown once): {pw}")
        elif args.cmd == "disable":
            store.disable(args.name)
            _audit("console.user", detail={"action": "disable"})
            print(f"console: '{args.name}' disabled")
        elif args.cmd == "list-users":
            for u in store.users():
                print(f"{u.username}\t{u.role}\t{u.mailbox or '-'}")
    except AuthError as exc:
        print(f"console: {exc}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
