HEADER = """-- {ruleset} v{version} — GENERATED by TrialBox criteria-compiler from Criterion IR (SPEC §6.3).
-- Deterministic template output; never edited by hand or produced by an LLM.
-- Parameters: $1 index_dates DATE[] ; $2 pids VARCHAR[] (NULL = all patients alive at index).
-- Output: one row per (pid, index_date) with "C_<ID>" BOOLEAN/NULL and "E_<ID>" VARCHAR per criterion.
"""


def lit(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def qcol(name: str) -> str:
    return '"' + name.replace('"', '""') + '"'


def date_bound(days: int) -> str:
    return "b.index_date" if days == 0 else f"(b.index_date + {days})"


def in_window(col: str, w: Window) -> str:
    hi = date_bound(w.to_days)
    if w.from_days is None:
        return f"{col} <= {hi}"
    return f"{col} BETWEEN {date_bound(w.from_days)} AND {hi}"


def cmp_sql(atom: Atom, value: str = "o.value_num", code: str = "o.value_code") -> str:
    v = atom.value
    assert v is not None and v.op is not None
    if v.op == "in":
        return f"({code} IN ({', '.join(lit(c) for c in v.codes or [])}))"
    if v.op == "between":
        assert v.num is not None and v.num2 is not None
        return f"({value} BETWEEN {fmt_num(v.num)} AND {fmt_num(v.num2)})"
    assert v.num is not None
    op = "=" if v.op == "=" else v.op
    return f"({value} {op} {fmt_num(v.num)})"


# D-142 (review B-01): a censored result ("<0.3": the true value is at most the bound, ">1000": at least) decides a
# comparison only when every value on that side of the bound gives the same answer; otherwise NULL (unknown). The
# bound is treated as reachable, so a strict "<0.3" is read as "<=0.3": that can only leave an answer unknown, never
# give a wrong one. (side, op) -> (when the bound is such that, the answer)
_CENSORED: dict[tuple[str, str], tuple[str, str]] = {
    ("below", ">="): ("{x} < {n}", "FALSE"),
    ("below", ">"): ("{x} <= {n}", "FALSE"),
    ("below", "<"): ("{x} < {n}", "TRUE"),
    ("below", "<="): ("{x} <= {n}", "TRUE"),
    ("below", "="): ("{x} < {n}", "FALSE"),
    ("below", "between"): ("{x} < {n}", "FALSE"),
    ("above", ">="): ("{x} >= {n}", "TRUE"),
    ("above", ">"): ("{x} > {n}", "TRUE"),
    ("above", "<"): ("{x} >= {n}", "FALSE"),
    ("above", "<="): ("{x} > {n}", "FALSE"),
    ("above", "="): ("{x} > {n}", "FALSE"),
    ("above", "between"): ("{x} > {n2}", "FALSE"),
}


def obs_cmp_sql(atom: Atom) -> str:
    """The comparison of one observation row: exact values as :func:`cmp_sql`; censored ones (``value_cmp``) only
    when decidable; no number (text, a coded answer) is NULL, never FALSE."""
    v = atom.value
    assert v is not None and v.op is not None
    plain = cmp_sql(atom)
    if v.op == "in":
        return plain
    assert v.num is not None
    n, n2 = fmt_num(v.num), fmt_num(v.num2) if v.num2 is not None else ""
    side: dict[str, str] = {}
    for s in ("below", "above"):
        cond, answer = _CENSORED[(s, v.op)]
        side[s] = f"CASE WHEN {cond.format(x='o.value_num', n=n, n2=n2)} THEN {answer} END"
    return (
        f"(CASE WHEN o.value_cmp IS NULL THEN {plain} "
        f"WHEN o.value_cmp IN ('<', '<=') THEN ({side['below']}) "
        f"WHEN o.value_cmp IN ('>', '>=') THEN ({side['above']}) END)"
    )


def _comment(text: str) -> str:
    """Criterion text for a ``--`` line comment: all whitespace (newlines from a reviewer's Alt+Enter or the model
    included) collapsed, so nothing after it can become SQL."""
    return " ".join(text.split())[:150]


class SqlGenerator:
    def __init__(self, ruleset: str, version: str, valuesets: ValueSets) -> None:
        self.ruleset = ruleset
        self.version = version
        self.vs = valuesets

    def _vs_match(self, vsname: str, system_col: str, code_col: str) -> str:
        return (
            f"EXISTS (SELECT 1 FROM vs WHERE vs.vs_id = {lit(vsname)} AND vs.system = {system_col} "
            f"AND vs.code = {code_col})"
        )

    # ------------------------------------------------------------------ per-atom CTEs; returns (ctes, expr, ev)
    def _family_offlist(self, vsname: str, system_col: str, code_col: str) -> str:
        """A code inside one of the grouper's families (D-113) that the ValueSet does not list. An ICD-10-CM family
        also holds the WHO ICD-10 codes of its prefix (baseline correction 3, D-205): a WHO code that is one of the
        listed ICD-10-CM codes is not off the list (the D-130 runtime check reads it, as before)."""
        who = ""
        if any(sy == SYSTEMS["icd10cm"] for sy, _ in self.vs.families(vsname)):
            who = (
                f" AND NOT ({system_col} = {lit(ICD10_WHO)} AND EXISTS (SELECT 1 FROM vs WHERE vs.vs_id = "
                f"{lit(vsname)} AND vs.system = {lit(SYSTEMS['icd10cm'])} AND vs.code = {code_col}))"
            )
        return (
            f"(EXISTS (SELECT 1 FROM vsf WHERE vsf.vs_id = {lit(vsname)} AND vsf.system = {system_col} "
            f"AND starts_with({code_col}, vsf.prefix)) AND NOT {self._vs_match(vsname, system_col, code_col)}{who})"
        )

    # (table, record id, date, [(system column, code column)]) per presence domain
    PRESENCE: ClassVar[dict[str, tuple[str, str, str, list[tuple[str, str]]]]] = {
        "condition": ("condition", "cid", "coalesce(onset, recorded)", [("x.system", "x.code")]),
        "medication": (
            "medication",
            "mid",
            "authored",
            [(lit(SYSTEMS["atc"]), "x.atc"), (lit(SYSTEMS["nhi_drug"]), "x.nhi_code")],
        ),
        "procedure": ("procedure", "prid", "performed", [("x.system", "x.code")]),
        "report": ("report", "rid", "effective", [("x.system", "x.code")]),
        "observation": ("observation", "oid", "effective::DATE", [("x.system", "x.code")]),
        "encounter": ("encounter", "eid", "start::DATE", [(lit(SYSTEMS["department"]), "x.dept")]),
        "claim": ("claim", "kid", "created", [(lit(SYSTEMS["nhi_drug"]), "x.product")]),
    }

    def _presence(self, name: str, atom: Atom, w: Window) -> tuple[list[str], str, str]:
        vsn = atom.valueset
        if atom.domain not in self.PRESENCE:
            raise CompileError(f"unsupported domain {atom.domain}")
        table, rid, d, cols = self.PRESENCE[atom.domain]
        rid_sel = "rid" if rid == "rid" else f"{rid} AS rid"

        def src(match: Callable[[str, str, str], str]) -> str:
            cond = " OR ".join(match(vsn, sc, cc) for sc, cc in cols)
            return f"SELECT pid, {rid_sel}, {d} AS d FROM {table} x WHERE {cond}"

        def cte(n: str, source: str) -> str:
            return (
                f"{n} AS (\n  SELECT b.pid, b.index_date, count(*) AS n,\n"
                f"         string_agg(e.rid || '|' || strftime(e.d, '%Y-%m-%d'), ';' ORDER BY e.d, e.rid) AS ev\n"
                f"  FROM base b JOIN ({source}) e ON e.pid = b.pid AND {in_window('e.d', w)}\n"
                f"  GROUP BY b.pid, b.index_date)"
            )

        quant = atom.quantifier or "any"
        n = f"coalesce({name}.n, 0)"
        # an undated record (no onset, no recorded date: a diagnosis carried over from an old system) cannot be
        # placed in the window: where the dated records do not settle the atom it is unknown (NULL), never a silent
        # false that lets an exclusion pass (scenario run DUMP-01). The same holds for every input that reaches the lake
        nd = f"{name}_nd"

        def listed_or_family(v: str, sc: str, cc: str) -> str:  # a grouper's off-list family code counts too (D-113)
            fam = f" OR {self._family_offlist(v, sc, cc)}" if self.vs.families(vsn) else ""
            return f"({self._vs_match(v, sc, cc)}{fam})"

        undated = (
            f"{nd} AS (\n  SELECT b.pid, b.index_date, count(*) AS n,\n"
            f"         string_agg(e.rid || '|', ';' ORDER BY e.rid) AS ev\n"
            f"  FROM base b JOIN ({src(listed_or_family)}) e ON e.pid = b.pid AND e.d IS NULL\n"
            f"  GROUP BY b.pid, b.index_date)"
        )
        u = f"coalesce({nd}.n, 0)"
        settled = f"({n} > 0)" if quant != "count>=" else f"({n} >= {atom.count})"
        reach = f"({u} > 0)" if quant != "count>=" else f"({n} + {u} >= {atom.count})"
        hit = "TRUE" if quant != "none" else "FALSE"
        miss = "FALSE" if quant != "none" else "TRUE"
        ctes = [cte(name, src(self._vs_match)), undated]
        if not self.vs.families(vsn):
            expr = f"(CASE WHEN {settled} THEN {hit} WHEN {reach} THEN NULL ELSE {miss} END)"
            return ctes, expr, f"coalesce({name}.ev, {nd}.ev)"
        # fail closed (D-113): when the listed codes do not settle the atom but the patient has a record coded inside
        # the grouper's family that the list lacks, the answer is unknown (NULL), never a silent false / true
        off = f"{name}_off"
        ctes.append(cte(off, src(self._family_offlist)))
        expr = (
            f"(CASE WHEN {settled} THEN {hit} WHEN coalesce({off}.n, 0) > 0 THEN NULL WHEN {reach} THEN NULL "
            f"ELSE {miss} END)"
        )
        return ctes, expr, f"coalesce({name}.ev, {off}.ev, {nd}.ev)"

    def _obs_source(self, vsname: str, w: Window) -> str:
        return (
            f"SELECT b.pid, b.index_date, o.oid, o.effective, o.value_num, o.value_cmp, o.value_code\n"
            f"  FROM base b JOIN observation o ON o.pid = b.pid AND {in_window('o.effective::DATE', w)}\n"
            f"  WHERE {self._vs_match(vsname, 'o.system', 'o.code')}"
        )

    def _obs_value(self, name: str, atom: Atom, w: Window) -> tuple[list[str], str, str]:
        quant = atom.quantifier or "any"
        src = self._obs_source(atom.valueset, w)
        if quant == "latest":
            cte = (
                f"{name} AS (\n  SELECT pid, index_date, {obs_cmp_sql(atom)} AS v,\n"
                f"         o.oid || '|' || strftime(o.effective, '%Y-%m-%d') AS ev\n"
                f"  FROM (SELECT *, row_number() OVER (PARTITION BY pid, index_date ORDER BY effective DESC, "
                f"oid DESC) AS rn\n        FROM ({src})) o WHERE rn = 1)"
            )
            return [cte], f"{name}.v", f"{name}.ev"
        c = obs_cmp_sql(atom)
        # D-142 (review B-01): a row whose comparison is NULL (no readable number) leaves the answer unknown unless
        # the readable rows settle it; it never counts as a failed test
        unread = f"count(*) FILTER (WHERE {c} IS NULL) > 0"
        anyv = f"(CASE WHEN bool_or({c}) THEN TRUE WHEN {unread} THEN NULL ELSE FALSE END)"
        if quant == "any":
            agg = anyv
        elif quant == "none":
            agg = f"(NOT {anyv})"
        elif quant == "all":
            agg = f"(CASE WHEN NOT bool_and({c}) THEN FALSE WHEN {unread} THEN NULL ELSE TRUE END)"
        elif quant == "count>=":
            met = f"count(*) FILTER (WHERE {c})"
            agg = (
                f"(CASE WHEN {met} >= {atom.count} THEN TRUE "
                f"WHEN {met} + count(*) FILTER (WHERE {c} IS NULL) >= {atom.count} THEN NULL ELSE FALSE END)"
            )
        else:
            raise CompileError(f"quantifier {quant}")
        cte = (
            f"{name} AS (\n  SELECT pid, index_date, {agg} AS v,\n"
            f"         string_agg(CASE WHEN {c} THEN o.oid || '|' || strftime(o.effective, '%Y-%m-%d') END, ';' "
            f"ORDER BY o.effective, o.oid) AS ev\n"
            f"  FROM ({src}) o GROUP BY pid, index_date)"
        )
        return [cte], f"{name}.v", f"{name}.ev"

    def _latest_component(self, name: str, comp: str, w: Window, near: tuple[str, int] | None = None) -> str:
        """The newest row of ``comp`` in the window (with ``near``: within that many days of the anchor component's
        row, the same-visit rule of D-149), its value converted to the formula's unit (``conv``; NULL when the unit
        is not allowed)."""
        system, code = CODES[comp]
        anchor = ""
        if near is not None:
            a, days = near
            anchor = (
                f"\n    JOIN {name}_{a} a ON a.pid = b.pid AND a.index_date = b.index_date"
                f" AND abs(date_diff('day', a.effective::DATE, o.effective::DATE)) <= {int(days)}"
            )
        return (
            f"{name}_{comp} AS (\n  SELECT pid, index_date, value_num, conv, oid, effective FROM (\n"
            f"    SELECT b.pid, b.index_date, o.value_num, {unit_sql(comp, 'o.value_num', 'o.unit')} AS conv, o.oid, "
            f"o.effective,\n"
            f"           row_number() OVER (PARTITION BY b.pid, b.index_date ORDER BY o.effective DESC, o.oid DESC)"
            f" AS rn\n    FROM base b JOIN observation o ON o.pid = b.pid AND {in_window('o.effective::DATE', w)}"
            f"{anchor}\n"
            f"    WHERE o.system = {lit(system)} AND o.code = {lit(code)}) WHERE rn = 1)"
        )

    def _derived(self, name: str, atom: Atom, w: Window) -> tuple[list[str], str, str]:
        """A score from its components (D-149): the same visit, units converted, and no value with a reason
        (``derived_missing_input:<c>`` / ``derived_unit:<c>`` in the evidence) when an input is missing or its unit
        does not fit: never FALSE."""
        assert atom.derived is not None
        score = atom.derived
        if score not in COMPONENTS:
            raise CompileError(f"derived {score}")
        comps = COMPONENTS[score]
        rule = SAME_VISIT.get(score)
        order = [rule[0], *[c for c in comps if c != rule[0]]] if rule else list(comps)
        ctes = [
            self._latest_component(name, c, w, (rule[0], rule[1][c]) if rule and c != rule[0] else None) for c in order
        ]
        joins = "\n  ".join(
            f"LEFT JOIN {name}_{c} {c} ON {c}.pid = b.pid AND {c}.index_date = b.index_date" for c in comps
        )
        v = {c: f"{c}.conv" for c in comps}

        def checks(cs: list[str]) -> list[tuple[str, str]]:  # (condition, reason) in the order they are reported
            out = []
            for c in cs:
                out.append((f"{c}.oid IS NULL OR {c}.value_num IS NULL", f"{MISSING}:{c}"))
                out.append((f"{c}.conv IS NULL", f"{UNIT}:{c}"))
            return out

        female = "(CASE WHEN b.sex IS NULL THEN NULL ELSE b.sex = 'female' END)"
        age = "date_sub('year', b.birth_date, b.index_date)"
        need = checks(list(comps))
        match score:
            case "bmi":
                value = f"{v['weight']} / pow({v['height']} / 100.0, 2)"
            case "egfr" | "egfr_ckd_epi":
                kappa = f"(CASE WHEN {female} THEN {EGFR['kappa_f']} ELSE {EGFR['kappa_m']} END)"
                alpha = f"(CASE WHEN {female} THEN {EGFR['alpha_f']} ELSE {EGFR['alpha_m']} END)"
                # least()/greatest() ignore NULLs in DuckDB: guard every input explicitly (CQL does the same)
                value = (
                    f"(CASE WHEN {v['creatinine']} IS NULL OR {age} IS NULL OR {female} IS NULL THEN NULL "
                    f"ELSE {EGFR['k']} * pow(least({v['creatinine']} / {kappa}, 1.0), {alpha}) * "
                    f"pow(greatest({v['creatinine']} / {kappa}, 1.0), {EGFR['exp_hi']}) * "
                    f"pow({EGFR['age_base']}, {age}) * (CASE WHEN {female} THEN {EGFR['female']} ELSE 1.0 END) "
                    f"END)"
                )
                need += [(f"{age} IS NULL", f"{MISSING}:age"), (f"{female} IS NULL", f"{MISSING}:sex")]
            case "egfr_jsn":
                value = (
                    f"(CASE WHEN {v['creatinine']} IS NULL OR {v['creatinine']} <= 0 OR {age} IS NULL OR {age} <= 0 "
                    f"OR {female} IS NULL THEN NULL "
                    f"ELSE {EGFR_JSN['k']} * pow({v['creatinine']}, {EGFR_JSN['scr_exp']}) * "
                    f"pow({age}, {EGFR_JSN['age_exp']}) * (CASE WHEN {female} THEN {EGFR_JSN['female']} ELSE 1.0 END) "
                    f"END)"
                )
                need += [(f"{age} IS NULL", f"{MISSING}:age"), (f"{female} IS NULL", f"{MISSING}:sex")]
            case "das28":
                base = (
                    f"{DAS28['tjc']} * sqrt({v['tjc28']}) + {DAS28['sjc']} * sqrt({v['sjc28']}) + "
                    f"{DAS28['gh']} * {v['ptga']}"
                )
                # ESR when the visit has one (its own unit must fit, and ln(0) is no value), else CRP
                value = (
                    f"(CASE WHEN {v['tjc28']} IS NULL OR {v['sjc28']} IS NULL OR {v['ptga']} IS NULL THEN NULL "
                    f"WHEN esr.oid IS NOT NULL THEN (CASE WHEN {v['esr']} > 0 THEN "
                    f"{base} + {DAS28['esr_ln']} * ln({v['esr']}) ELSE NULL END) "
                    f"WHEN {v['crp']} IS NOT NULL THEN {base} + {DAS28['crp_ln']} * ln({v['crp']} + 1) + "
                    f"{DAS28['crp_const']} ELSE NULL END)"
                )
                need = [
                    *checks(["tjc28", "sjc28", "ptga"]),
                    ("esr.oid IS NOT NULL AND esr.value_num IS NULL", f"{MISSING}:esr"),
                    ("esr.oid IS NOT NULL AND esr.conv IS NULL", f"{UNIT}:esr"),
                    ("esr.oid IS NOT NULL AND esr.conv <= 0", f"{MISSING}:esr"),
                    *checks(["crp"]),
                ]
            case "basdai":
                q = [v[f"basdai_q{i}"] for i in range(1, 7)]
                value = f"(({q[0]} + {q[1]} + {q[2]} + {q[3]} + ({q[4]} + {q[5]}) / 2.0) / 5.0)"
            case "asdas":
                value = (
                    f"({ASDAS['back']} * {v['basdai_q2']} + {ASDAS['stiff']} * {v['basdai_q6']} + "
                    f"{ASDAS['ptga']} * ({v['ptga']} / 10.0) + {ASDAS['periph']} * {v['basdai_q3']} + "
                    f"{ASDAS['crp_ln']} * ln({v['crp']} + 1))"
                )
            case _:
                raise CompileError(f"derived {score}")
        refs = (
            "concat_ws(';', " + ", ".join(f"{c}.oid || '|' || strftime({c}.effective, '%Y-%m-%d')" for c in comps) + ")"
        )
        why = "(CASE " + " ".join(f"WHEN {cond} THEN {lit(r)}" for cond, r in need) + f" ELSE {lit(MISSING)} END)"
        ctes.append(
            f"{name}_v AS (\n  SELECT b.pid, b.index_date, {value} AS val, {refs} AS refs,\n"
            f"         {why} AS why\n  FROM base b\n  {joins})"
        )
        ctes.append(
            f"{name} AS (\n  SELECT pid, index_date, val, CASE WHEN val IS NULL THEN why ELSE refs END AS ev\n"
            f"  FROM {name}_v)"
        )
        expr = (
            cmp_sql(atom, value=f"{name}.val")
            if atom.value is not None
            else f"(CASE WHEN {name}.val IS NULL THEN NULL ELSE TRUE END)"
        )
        return ctes, expr, f"{name}.ev"

    def _med_duration(self, name: str, atom: Atom, w: Window) -> tuple[list[str], str, str]:
        assert atom.duration is not None and atom.duration.min_days is not None
        gap = 30 if atom.duration.gap_days is None else atom.duration.gap_days
        lo = "DATE '1900-01-01'" if w.from_days is None else date_bound(w.from_days)
        hi = date_bound(w.to_days)
        match = (
            f"({self._vs_match(atom.valueset, lit(SYSTEMS['atc']), 'm.atc')} OR "
            f"{self._vs_match(atom.valueset, lit(SYSTEMS['nhi_drug']), 'm.nhi_code')})"
        )
        ctes = [
            (
                f"{name}_p AS (\n  SELECT b.pid, b.index_date, m.mid, greatest(coalesce(m.start, m.authored), {lo}) AS s,\n"
                f'         least(coalesce(m."end", m.start, m.authored), {hi}) AS e\n'
                f"  FROM base b JOIN medication m ON m.pid = b.pid\n  WHERE {match}\n"
                # greatest/least skip NULLs: an order without any date would span the whole window
                f"    AND coalesce(m.start, m.authored) IS NOT NULL\n"
                f'    AND greatest(coalesce(m.start, m.authored), {lo}) <= least(coalesce(m."end", m.start, m.authored), '
                f"{hi}))"
            ),
            (
                f"{name}_g AS (\n  SELECT *, CASE WHEN s <= max(e) OVER (PARTITION BY pid, index_date ORDER BY s, e, mid "
                f"ROWS BETWEEN UNBOUNDED PRECEDING AND 1 PRECEDING) + {gap + 1} THEN 0 ELSE 1 END AS new_island\n"
                f"  FROM {name}_p)"
            ),
            (
                f"{name}_i AS (\n  SELECT *, sum(new_island) OVER (PARTITION BY pid, index_date ORDER BY s, e, mid "
                f"ROWS UNBOUNDED PRECEDING) AS island FROM {name}_g)"
            ),
            (
                f"{name} AS (\n  SELECT pid, index_date, max(len) AS days, "
                f"string_agg(ev, ';' ORDER BY ev) AS ev FROM (\n"
                f"    SELECT pid, index_date, island, (max(e) - min(s)) + 1 AS len,\n"
                f"           string_agg(mid, ';' ORDER BY s, mid) AS ev FROM {name}_i GROUP BY pid, index_date, island)\n"
                f"  GROUP BY pid, index_date)"
            ),
        ]
        return ctes, f"(coalesce({name}.days, 0) >= {atom.duration.min_days})", f"{name}.ev"

    def _demographic(self, atom: Atom) -> tuple[list[str], str, str]:
        conds = []
        age = "date_sub('year', b.birth_date, b.index_date)"
        if atom.age is not None:
            if atom.age.min is not None:
                conds.append(f"({age} >= {fmt_num(atom.age.min)})")
            if atom.age.max is not None:
                conds.append(f"({age} <= {fmt_num(atom.age.max)})")
        if atom.sex is not None:
            conds.append(f"(CASE WHEN b.sex IS NULL THEN NULL ELSE b.sex = {lit(atom.sex)} END)")
        return [], "(" + " AND ".join(conds) + ")", "NULL"

    # ------------------------------------------------------------------ assembly
    def _bool(self, expr: Atom | BoolExpr, names: dict[int, str]) -> str:
        if isinstance(expr, Atom):
            return names[id(expr)]
        parts = [self._bool(a, names) for a in expr.args]
        if expr.op == "not":
            return f"(NOT {parts[0]})"
        return "(" + f" {expr.op.upper()} ".join(parts) + ")"

    def render(self, criteria: list[CriterionIR]) -> str:
        ctes: list[str] = []
        selects: list[str] = []
        final_joins: list[str] = []
        used_vs: set[str] = set()
        for c in compiled(criteria):
            check_bool(c.logic)
            names: dict[int, str] = {}
            evs: list[str] = []
            joins: list[str] = []
            for n, atom in enumerate(atoms(c.logic), start=1):
                k = kind(atom)
                w = window(atom)
                aname = f"a_{ident(c.id)}_{n}".lower()
                if k is Kind.PRESENCE:
                    cs, expr, ev = self._presence(aname, atom, w)
                elif k is Kind.OBS_VALUE:
                    cs, expr, ev = self._obs_value(aname, atom, w)
                elif k is Kind.DERIVED:
                    cs, expr, ev = self._derived(aname, atom, w)
                elif k is Kind.MED_DURATION:
                    cs, expr, ev = self._med_duration(aname, atom, w)
                else:
                    cs, expr, ev = self._demographic(atom)
                if atom.domain != "demographic" and atom.derived is None:
                    used_vs.add(atom.valueset)
                ctes.extend(cs)
                if cs:
                    joins.append(f"LEFT JOIN {aname} ON {aname}.pid = b.pid AND {aname}.index_date = b.index_date")
                if k is Kind.PRESENCE:  # the undated records and, for a grouper, the off-list family
                    for extra in cs[1:]:
                        x = extra.split(" AS (", 1)[0]
                        joins.append(f"LEFT JOIN {x} ON {x}.pid = b.pid AND {x}.index_date = b.index_date")
                names[id(atom)] = expr
                evs.append(ev)
            crit = f"c_{ident(c.id)}".lower()
            ctes.append(
                f"-- {c.id} ({c.kind}): {_comment(c.text)}\n{crit} AS (\n"
                f"  SELECT b.pid, b.index_date, {self._bool(c.logic, names)} AS v,\n"
                f"         concat_ws(';', {', '.join(evs)}) AS ev\n  FROM base b\n  "
                + ("\n  ".join(joins) if joins else "")
                + ")"
            )
            selects.append(f"{crit}.v AS {qcol('C_' + c.id)}, {crit}.ev AS {qcol('E_' + c.id)}")
            final_joins.append(f"LEFT JOIN {crit} ON {crit}.pid = b.pid AND {crit}.index_date = b.index_date")
        vs_rows = []
        for v in sorted(used_vs):
            for system, code in self.vs.codes(v):
                vs_rows.append(f"({lit(v)}, {lit(system)}, {lit(code)})")
        if not vs_rows:
            vs_rows.append("('__none__', '', '')")
        fam_rows = [
            f"({lit(v)}, {lit(sy)}, {lit(prefix)})"
            for v in sorted(used_vs)
            for system, prefix in self.vs.families(v)
            for sy in family_systems(system)
        ]
        prelude = [
            "params AS (SELECT CAST($1 AS DATE[]) AS idx_dates, CAST($2 AS VARCHAR[]) AS pids)",
            "idx AS (SELECT unnest(idx_dates) AS index_date FROM params)",
            (
                "base AS (\n  SELECT p.pid, p.birth_date, p.sex, i.index_date FROM patient p CROSS JOIN idx i\n"
                "  WHERE ((SELECT pids FROM params) IS NULL OR list_contains((SELECT pids FROM params), p.pid))\n"
                "    AND (p.deceased_date IS NULL OR p.deceased_date > i.index_date)\n"
                "    AND (p.birth_date IS NULL OR p.birth_date <= i.index_date))"
            ),
            "vs(vs_id, system, code) AS (VALUES\n  " + ",\n  ".join(vs_rows) + ")",
        ]
        if fam_rows:
            prelude.append("vsf(vs_id, system, prefix) AS (VALUES\n  " + ",\n  ".join(fam_rows) + ")")
        body = ",\n".join(prelude + ctes)
        return (
            HEADER.format(ruleset=self.ruleset, version=self.version)
            + "WITH\n"
            + body
            + "\nSELECT b.pid, b.index_date,\n  "
            + ",\n  ".join(selects)
            + "\nFROM base b\n"
            + "\n".join(final_joins)
            + "\nORDER BY b.pid, b.index_date\n"
        )
