"""Service-to-service token between the console (and the mail gateway, the channel relay) and the orchestrator (D-114).

Fable review 2026-11-08, finding 3: anything on the compose ``trialbox-net`` could ``POST /jobs/{id}/reveal`` and get
a chart number under any name. Now every changing call to the orchestrator carries ``X-TB-Service-Token``; the token
is one shared secret per box (``TB_SERVICE_TOKEN`` in ``deploy/.env``, generated by ``install.sh`` / ``poc.sh``, or a
file named by ``TB_SERVICE_TOKEN_FILE``). The caller's signed-in user travels in ``X-TB-Actor``; the orchestrator
takes the audit actor from it, not from a body field, because only a token holder can set it.

Without a token: DEV and TEST boxes (tests, ``make demo``) accept unauthenticated calls; any other ``TB_ENV`` refuses
every changing call with 503 until a token is configured (fail closed).
"""

from __future__ import annotations

import hmac
import os
from pathlib import Path
from urllib.parse import quote, unquote

TOKEN_HEADER = "X-TB-Service-Token"
ACTOR_HEADER = "X-TB-Actor"
OPEN_ENVS = ("DEV", "TEST")
SAFE_METHODS = ("GET", "HEAD", "OPTIONS")


def service_token() -> str:
    """The box's token, or "" when none is configured (a ``change-me`` placeholder counts as none)."""
    tok = (os.environ.get("TB_SERVICE_TOKEN") or "").strip()
    path = (os.environ.get("TB_SERVICE_TOKEN_FILE") or "").strip()
    if not tok and path:
        try:
            tok = Path(path).read_text(encoding="utf-8").strip()
        except OSError:
            tok = ""
    return "" if tok.startswith("change-me") else tok


def auth_headers(actor: str | None = None) -> dict[str, str]:
    """Headers for a call to the orchestrator: the token when configured, the signed-in user when given."""
    h: dict[str, str] = {}
    tok = service_token()
    if tok:
        h[TOKEN_HEADER] = tok
    if actor:
        h.update(actor_header(actor))
    return h


def actor_header(actor: str) -> dict[str, str]:
    """``X-TB-Actor`` for a signed-in user; percent-encoded, as a header is ASCII and names may be 日本語."""
    return {ACTOR_HEADER: quote(actor, safe="@._-+")}


def check(method: str, presented: str | None, environment: str) -> tuple[int, str] | None:
    """None when the call may proceed; else (status, detail). Read-only methods always pass."""
    if method.upper() in SAFE_METHODS:
        return None
    tok = service_token()
    if not tok:
        if environment.upper() in OPEN_ENVS:
            return None
        return 503, "no service token configured (TB_SERVICE_TOKEN): changing calls are refused"
    if not presented:
        return 401, f"missing {TOKEN_HEADER}"
    if not hmac.compare_digest(presented.encode("utf-8"), tok.encode("utf-8")):
        return 403, f"wrong {TOKEN_HEADER}"
    return None


def actor_of(header: str | None, fallback: str | None) -> str | None:
    """The audit actor: the ``X-TB-Actor`` header of an authenticated caller; the body or query ``by`` only on a box
    without a token (DEV/TEST), where nobody is authenticated anyway."""
    if header and header.strip():
        return unquote(header.strip())[:200]
    if not service_token() and fallback and fallback.strip():
        return fallback.strip()[:200]
    return None
